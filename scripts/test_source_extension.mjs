// Exercise the actual generated extension using the same function-body contract as WebKit.
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

const directory = process.argv[2];
assert(directory, 'Pass the directory generated by build_source_repository.py');
const manifest = JSON.parse(readFileSync(join(directory, 'repository.json')));
const extension = manifest.extensions[0];
const code = readFileSync(join(directory, 'source.js'), 'utf8');
assert.equal(extension.sha256, createHash('sha256').update(code).digest('hex'));
const catalog = JSON.parse(readFileSync(join(directory, 'catalog.json')));
let requests = 0;
const api = Object.freeze({request: async url => {
  requests++;
  assert.equal(new URL(url).host, extension.hosts[0]);
  assert(url.endsWith('/catalog.json'));
  return {json: () => structuredClone(catalog), text: JSON.stringify(catalog)};
}});
const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
const call = new AsyncFunction('operation', 'input', 'api', code + '\nreturn JSON.stringify(await source[operation](input, api));');
const all = JSON.parse(await call('search', {query: ''}, api));
assert.equal(all.length, 3);
assert(!('chapters' in all[0]));
assert.equal(JSON.parse(await call('search', {query: 'pApEr'}, api))[0].id, 'moon');
assert.deepEqual(JSON.parse(await call('search', {query: 'nonexistent'}, api)), []);
for (const title of all) {
  const chapters = JSON.parse(await call('chapters', {mangaID: title.id}, api));
  assert.equal(chapters.length, 1);
  assert(chapters[0].credit);
  const pages = JSON.parse(await call('pages', {mangaID: title.id, chapterID: chapters[0].id}, api));
  assert.equal(pages.length, 1);
  assert.equal(new URL(pages[0]).host, extension.hosts[0]);
  assert(existsSync(join(directory, new URL(pages[0]).pathname.split('/').at(-1))));
}
await assert.rejects(call('chapters', {mangaID: 'removed'}, api), /no longer available/);
await assert.rejects(call('pages', {mangaID: 'moon', chapterID: 'removed'}, api), /no longer available/);
assert.equal(requests, 11);
console.log('PASS: generated repository SHA-256, actual JS search → chapters → pages, credits, images and missing-content errors');
